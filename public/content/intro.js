<h3>Goの強み</h3>
<ul>
<li><strong>シンプルで覚えることが少ない</strong>：文法が意図的に小さく作られている（ループはforだけ、例外機構なし、継承なし）。数週間でチームの誰もが読めるコードを書けるようになる。</li>
<li><strong>並行処理が簡単</strong>：ゴルーチンとチャネルという仕組みで、数千の処理を同時に走らせるプログラムが手軽に書ける。Webサーバーとの相性が抜群。</li>
<li><strong>コンパイルが速く、配布も簡単</strong>：ビルドは一瞬で、依存を含んだ1つの実行ファイルができる。Dockerイメージも小さくできる。</li>
